-- ============================================================
-- 4. USER PROFILES
-- Safe user information for admin dashboard
-- ============================================================

create table if not exists public.profiles (
    user_id uuid primary key
        references auth.users(id) on delete cascade,

    email text not null default '',

    created_at timestamptz not null default now(),

    last_sign_in_at timestamptz,

    email_confirmed boolean not null default false,

    display_name text not null default '',

    status text not null default 'active'
        check (
            status in ('active', 'suspended')
        )
);

-- Synchronize profiles with Supabase Auth.
create or replace function public.sync_profile_from_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin

    insert into public.profiles (
        user_id,
        email,
        created_at,
        last_sign_in_at,
        email_confirmed
    )
    values (
        new.id,
        coalesce(new.email, ''),
        new.created_at,
        new.last_sign_in_at,
        new.email_confirmed_at is not null
    )

    on conflict (user_id)
    do update set
        email = excluded.email,
        last_sign_in_at = excluded.last_sign_in_at,
        email_confirmed = excluded.email_confirmed;

    return new;

end;
$$;

-- Synchronize new and updated authentication users.
drop trigger if exists profiles_sync_on_user
on auth.users;

create trigger profiles_sync_on_user
after insert or update on auth.users
for each row
execute function public.sync_profile_from_user();

-- Backfill existing accounts.
insert into public.profiles (
    user_id,
    email,
    created_at,
    last_sign_in_at,
    email_confirmed
)
select
    u.id,
    coalesce(u.email, ''),
    u.created_at,
    u.last_sign_in_at,
    u.email_confirmed_at is not null
from auth.users u

on conflict (user_id)
do nothing;

alter table public.profiles enable row level security;

drop policy if exists "Admins can read profiles"
on public.profiles;

drop policy if exists "Admins can update profiles"
on public.profiles;

-- Users can read their own profile.
-- Admins can read all profiles.
create policy "Admins can read profiles"
on public.profiles
for select
to authenticated
using (
    public.is_current_user_admin()
    or user_id = (select auth.uid())
);

-- Only admins can update profiles.
create policy "Admins can update profiles"
on public.profiles
for update
to authenticated
using (
    public.is_current_user_admin()
)
with check (
    public.is_current_user_admin()
);

revoke all on table public.profiles
from anon, authenticated;

grant select, update
on public.profiles
to authenticated;

create index if not exists idx_profiles_created_at
on public.profiles(created_at desc);


