begin;

-- ============================================================
-- 1. ADMIN USERS
-- ============================================================

create table if not exists public.admin_users (
    user_id uuid primary key
        references auth.users(id) on delete cascade,

    granted_by uuid
        references auth.users(id) on delete set null,

    granted_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

-- Prevent ordinary users from modifying admin assignments.
revoke all on table public.admin_users from anon, authenticated;

-- Admin authorization function.
create or replace function public.is_current_user_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.admin_users
        where user_id = (select auth.uid())
    );
$$;

-- Remove default PUBLIC execution permissions.
revoke all on function public.is_current_user_admin()
from public, anon;

grant execute on function public.is_current_user_admin()
to authenticated;

-- Admins can read admin assignments.
drop policy if exists "Admins can read admin grants"
on public.admin_users;

create policy "Admins can read admin grants"
on public.admin_users
for select
to authenticated
using (public.is_current_user_admin());

grant select on public.admin_users to authenticated;


-- ============================================================
-- 2. REQUESTS
-- Contact, partner/team and support enquiries
-- ============================================================

create table if not exists public.requests (
    id bigint generated by default as identity primary key,

    request_type text not null
        check (
            request_type in ('contact', 'partner', 'support')
        ),

    name text not null default '',
    email text not null default '',
    phone text not null default '',
    message text not null default '',

    details jsonb not null default '{}'::jsonb,

    status text not null default 'pending'
        check (
            status in ('pending', 'in_progress', 'resolved')
        ),

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    updated_by uuid
        references auth.users(id) on delete set null
);

-- Automatically update updated_at.
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists requests_touch_updated_at
on public.requests;

create trigger requests_touch_updated_at
before update on public.requests
for each row
execute function public.touch_updated_at();

alter table public.requests enable row level security;

-- Remove previous request policies.
drop policy if exists "Anyone may submit a request"
on public.requests;

drop policy if exists "Admins can read requests"
on public.requests;

drop policy if exists "Admins can update requests"
on public.requests;

-- Public visitors can submit pending requests only.
create policy "Anyone may submit a request"
on public.requests
for insert
to anon, authenticated
with check (
    request_type in ('contact', 'partner', 'support')
    and status = 'pending'
    and updated_by is null
);

-- Only admins can read requests.
create policy "Admins can read requests"
on public.requests
for select
to authenticated
using (
    public.is_current_user_admin()
);

-- Only admins can update requests.
create policy "Admins can update requests"
on public.requests
for update
to authenticated
using (
    public.is_current_user_admin()
)
with check (
    public.is_current_user_admin()
);

-- Restrict public submission to form fields.
revoke all on table public.requests
from anon, authenticated;

grant insert (
    request_type,
    name,
    email,
    phone,
    message,
    details
)
on public.requests
to anon, authenticated;

grant select, update
on public.requests
to authenticated;

-- Prevent public deletion.
revoke delete on public.requests
from anon, authenticated;

create index if not exists idx_requests_type
on public.requests(request_type);

create index if not exists idx_requests_status
on public.requests(status);

create index if not exists idx_requests_created_at
on public.requests(created_at desc);


