-- Run this migration explicitly after legal and schema review; it is not applied by the app.
create table if not exists public.terms_acceptances (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  terms_version text not null,
  content_hash text not null,
  accepted_at timestamptz not null default timezone('utc', now()),
  created_at timestamptz not null default timezone('utc', now()),
  unique (user_id, terms_version)
);

alter table public.terms_acceptances enable row level security;

drop policy if exists "Users can view their own terms acceptances" on public.terms_acceptances;
create policy "Users can view their own terms acceptances"
  on public.terms_acceptances for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can record their own terms acceptance" on public.terms_acceptances;
create policy "Users can record their own terms acceptance"
  on public.terms_acceptances for insert
  to authenticated
  with check (auth.uid() = user_id);

revoke all on table public.terms_acceptances from anon;
grant select, insert on table public.terms_acceptances to authenticated;
grant usage, select on sequence public.terms_acceptances_id_seq to authenticated;
